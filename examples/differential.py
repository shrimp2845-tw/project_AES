def sha256(data: str) -> bytes:
    return hashlib.sha256(data.encode()).hexdigest()

def check_symmetric(conf: AESConfig, kl = 128) -> bool:
    pt = os.urandom(16)
    key = os.urandom(kl//16)
    cipher = AES(key, conf)
    return pt == cipher.decrypt_block(cipher.encrypt_block(pt))

def get_dy(x: int, dx: int, conf: AESConfig) -> int:
    box = conf.custom_sbox
    if not box:
        box = SBOX
    dy = sbox(x, table = box) ^ sbox(x ^ dx, table = box)
    return dy

def build_ddt(conf: AESConfig) -> list[list[int]]:
    ddt =[[0]*256 for i in range(256)]
    for x in range(256):
        for dx in range(256):
            ddt[dx][get_dy(x, dx, conf)] += 1
    return ddt

def save_ddt_csv(ddt):
    filename = f"{PATH}{sha256(str(ddt))}.csv"
    with open(filename, "w", newline = "") as f:
        writer = csv.writer(f)
        writer.writerows(ddt)
    print(f'sucess! \nhash: {sha256(str(ddt))}')

def max_ddt(ddt):
    m = 0
    for dx in range(1, 256):
        for dy in range(256):
            m = max(m, ddt[dx][dy])
    return m

